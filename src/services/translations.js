export function translateText(value, language = null) {
  if (language === null) language = getPreferredLanguage()
  return language === 'Hindi' ? (hindi[value] ?? value) : value
}

export function getPreferredLanguage() {
  try { return JSON.parse(localStorage.getItem('ruralattend-language') ?? '"English"') } catch { return 'English' }
}
